export const dictionaries: Record<Locale, Dictionary> = { ro, en };

export const I18n = createContext<{ locale: Locale; t: Dictionary }>({ locale: 'ro', t: ro });

export function useI18n(): { locale: Locale; t: Dictionary } {
  return useContext(I18n);
}

export function formatTime(iso: string, locale: Locale): string {
  return new Date(iso).toLocaleTimeString(locale === 'en' ? 'en-GB' : 'ro-RO', {
    hour: '2-digit',
    minute: '2-digit',
  });
}
